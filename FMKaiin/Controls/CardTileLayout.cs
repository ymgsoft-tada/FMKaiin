namespace App.Controls
{
    /// <summary>
    /// <see cref="CardTileButton"/> の中での、アイコンと文字列の並べ方。
    /// </summary>
    public enum CardTileLayout
    {
        /// <summary>アイコンを左、文字列をその右に並べる（横並び）。文字列は左寄せ。</summary>
        Horizontal = 0,
        /// <summary>アイコンを上、文字列をその下に並べる（縦並び）。どちらも左右中央。</summary>
        Vertical
    }
}

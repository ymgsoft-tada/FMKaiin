        /// <summary>
        /// ロゴの形のパスを作る。24×24 の設計グリッド上の座標になっている。呼び出し側で Dispose すること。
        /// </summary>
        public static GraphicsPath CreatePath()
        {
            var path = new GraphicsPath(FillMode.Alternate);
            foreach (float[] outline in Outlines)
            {
                var points = new PointF[outline.Length / 2];
                for (int i = 0; i < points.Length; i++)
                {
                    points[i] = new PointF(outline[i * 2], outline[i * 2 + 1]);
                }
                path.AddPolygon(points);
            }
            return path;
        }
